function buildNoticeTemplates(): { key: string; re: RegExp }[] {
  const keys = new Set(
    zhHansKeys().filter(
      (k) =>
        NOTICE_PREFIXES.some((p) => k.startsWith(p)) &&
        k.split(/%@|%d/).join("").trim().length >= 12,
    ),
  );
  for (const k of EXTRA_NOTICE_KEYS) if (k in zhHans) keys.add(k);
  return [...keys]
    .sort(
      (a, b) =>
        b.split(/%@|%d/).join("").length - a.split(/%@|%d/).join("").length,
    )
    .map((key) => {
      if (key === PATCH_LANDING_KEY) {
        const parts = key.split(/%@|%d/).map(escapeRe);
        return {
          key,
          re: new RegExp(
            "^" + parts[0] + "(.+?)" + parts[1] + "(.+?)" + parts[2] + "(.*?)" + parts[3] + "(.+?)" + parts[4] + "$",
            "s",
          ),
        };
      }
      if (key === "%@ at %@") {
        return {
          key,
          re: new RegExp(`^${WEEKDAY_PATTERN} at (.+?)$`),
        };
      }
      const flags = SINGLE_LINE_DETAIL_KEYS.has(key) ? "" : "s";
      return {
        key,
        re: new RegExp(
          "^" + key.split(/%@|%d/).map(escapeRe).join("(.+?)") + "$",
          flags,
        ),
      };
    });
}

/**
 * Engine-emitted notices carry already-substituted English — a catalog
 * key like "Hydra: %@ is a system folder, so %@ did not start." never
 * matches the literal text, so a zh-Hans UI would read English. Recover
 * the template by matching every parameterized key against the message,
 * then translate with the captured values. Falls back to the prefix
 * path for untemplated notices.
 */
export function translateNotice(
  t: (k: string, ...vars: string[]) => string,
  message: string,
): string {
  noticeTemplates ??= buildNoticeTemplates();
  for (const { key, re } of noticeTemplates) {
    const m = re.exec(message);
    if (!m) continue;
    const args = m.slice(1);
    if (key === PATCH_LANDING_KEY && args[2]) {
      args[2] = translateNotice(t, args[2]);
    } else if (key === "Why it did not land: %@.\n\n" && args[0]) {
      args[0] = translateError(t, args[0]);
    } else if (key === "Usage limit reached. Continuing automatically at %@." && args[0]) {
      args[0] = translateNotice(t, args[0]);
    } else if (key === "%@ at %@" && args[0]) {
      args[0] = t(args[0]);
    } else if (
      (key === "⚠ Automatic continue failed: %@" ||
        key === "The head could not start: %@" ||
        key === "Queued message could not be sent: %@" ||
        key === "Codex error (retrying): %@" ||
        key === "interrupt request failed: %@" ||
        key === "question answer %@ — the request was expired unanswered" ||
        key === "approval answer %@ — the request was expired unanswered") &&
      args[0]
    ) {
      args[0] = translateError(t, args[0]);
    }
    return t(key, ...args);
  }
  return translateError(t, message);
}

const DETAIL_CLAUSE_BOUNDARY =
  /, (?=(?:network access(?:, |$)|(?:cwd|requested write root|read|write|deny): |glob scan depth ))/;
const DETAIL_PREFIX_KEYS: ReadonlyArray<readonly [prefix: string, key: string]> = [
  ["cwd: ", "cwd: %@"],
  ["requested write root: ", "requested write root: %@"],
  ["read: ", "read: %@"],
  ["write: ", "write: %@"],
  ["deny: ", "deny: %@"],
  ["glob scan depth ", "glob scan depth %@"],
];

function translateDetailClause(
  t: (k: string, ...vars: string[]) => string,
  clause: string,
): string {
  if (clause === "network access") return t("network access");
  for (const [prefix, key] of DETAIL_PREFIX_KEYS) {
    if (clause.startsWith(prefix) && clause.length > prefix.length) {
      return t(key, clause.slice(prefix.length));
    }
  }
  return translateNotice(t, clause);
}

/** Translate approval / permission detail lines (newline- or comma-joined grants). */
export function translateDetail(
  t: (k: string, ...vars: string[]) => string,
  detail: string,
): string {
  return detail
    .split("\n")
    .map((line) => {
      if (line === "") return "";
      const clauses = line.split(DETAIL_CLAUSE_BOUNDARY);
      return clauses.map((c) => translateDetailClause(t, c)).join(t(", "));
    })
    .join("\n");
}

